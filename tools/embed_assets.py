# Turns every .tga file in assets/ into a C++ header in include/,
# so the image's bytes get built into the program.
#
#   assets/fish.tga  ->  include/fish_tga.h  containing
#                        const uint8_t fish_tga[] = { ... };
#                        const unsigned int fish_tga_len = ...;
#
# PlatformIO runs this automatically before every build, because
# platformio.ini has:   extra_scripts = pre:tools/embed_assets.py
# So to change the fish: save over assets/fish.tga and press Upload.
#
# You can also run it by hand:   python tools/embed_assets.py

import os

EMBED_EXTENSIONS = (".tga",)   # which files in assets/ to turn into headers
BYTES_PER_LINE = 12

# List headers: each one gathers a group of images into one array.
#   (header file, array name, count name, which files belong in it)
LIST_HEADERS = [
    ("koi_patterns.h", "KOI_PATTERNS", "NUM_KOI_PATTERNS", lambda name: name.startswith("koi")),
    ("lilypads.h",     "LILYPADS",     "NUM_LILYPADS",     lambda name: "lilypad" in name),
]

try:
    Import("env")                               # only exists when PlatformIO runs us
    project_dir = env.subst("$PROJECT_DIR")
except NameError:                               # run by hand
    project_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

assets_dir = os.path.join(project_dir, "assets")
include_dir = os.path.join(project_dir, "include")


def make_header(file_name, data):
    # "fish.tga" -> "fish_tga"  (must be a valid C++ name)
    array_name = "".join(c if c.isalnum() else "_" for c in file_name)

    lines = []
    for start in range(0, len(data), BYTES_PER_LINE):
        chunk = data[start:start + BYTES_PER_LINE]
        lines.append("  " + ", ".join("0x%02x" % byte for byte in chunk))

    return (
        "// GENERATED by tools/embed_assets.py from assets/%s. Don't edit this file:\n"
        "// edit assets/%s instead, and this file is rebuilt on the next build.\n"
        "#pragma once\n"
        "#include <stdint.h>\n"
        "\n"
        "const uint8_t %s[] = {\n"
        "%s\n"
        "};\n"
        "const unsigned int %s_len = %d;\n"
    ) % (file_name, file_name, array_name, ",\n".join(lines), array_name, len(data)), array_name


def make_image_struct_header():
    # The struct every list header uses. It lives in its own header so that
    # including koi_patterns.h and lilypads.h together doesn't define it twice.
    return (
        "// GENERATED by tools/embed_assets.py. Don't edit this file.\n"
        "#pragma once\n"
        "#include <stdint.h>\n"
        "\n"
        "struct EmbeddedImage {\n"
        "  const char    *name;    // file name without .tga\n"
        "  const uint8_t *data;    // the file's bytes\n"
        "  unsigned int   length;  // how many bytes\n"
        "};\n"
    )


def make_list_header(entries, list_name, count_name):
    # entries: list of (file_name, array_name)
    # One header that includes every image in a group and lists them in an
    # array, so main.cpp can loop over them instead of including each by hand.
    includes = "".join('#include "%s.h"\n' % array_name for _, array_name in entries)

    if entries:
        rows = "".join(
            '  { "%s", %s, %s_len },\n' % (os.path.splitext(file_name)[0], array_name, array_name)
            for file_name, array_name in entries
        )
        array = "static const EmbeddedImage %s[] = {\n%s};\n" % (list_name, rows)
    else:
        array = "static const EmbeddedImage *%s = nullptr;  // no matching .tga files in assets/\n" % list_name

    return (
        "// GENERATED by tools/embed_assets.py from .tga files in assets/. Don't edit\n"
        "// this file: add or remove images in assets/ and it's rebuilt on the next build.\n"
        "#pragma once\n"
        '#include "embedded_image.h"\n'
        "%s"
        "\n"
        "%s"
        "static const int %s = %d;\n"
    ) % (includes, array, count_name, len(entries))


def write_if_changed(path, text):
    # Only rewrite the header if it actually changed, so unchanged art
    # doesn't force the code to recompile.
    old_text = None
    if os.path.exists(path):
        with open(path) as f:
            old_text = f.read()
    if text == old_text:
        return False
    with open(path, "w") as f:
        f.write(text)
    return True


os.makedirs(include_dir, exist_ok=True)
groups = {header: [] for header, _, _, _ in LIST_HEADERS}
for file_name in sorted(os.listdir(assets_dir)):
    if not file_name.lower().endswith(EMBED_EXTENSIONS):
        continue

    with open(os.path.join(assets_dir, file_name), "rb") as f:
        data = f.read()
    header_text, array_name = make_header(file_name, data)
    for header, _, _, belongs in LIST_HEADERS:
        if belongs(file_name.lower()):
            groups[header].append((file_name, array_name))

    if write_if_changed(os.path.join(include_dir, array_name + ".h"), header_text):
        print("embed_assets: assets/%s -> include/%s.h (%d bytes)" % (file_name, array_name, len(data)))

write_if_changed(os.path.join(include_dir, "embedded_image.h"), make_image_struct_header())
for header, list_name, count_name, _ in LIST_HEADERS:
    text = make_list_header(groups[header], list_name, count_name)
    if write_if_changed(os.path.join(include_dir, header), text):
        print("embed_assets: include/%s (%d images)" % (header, len(groups[header])))
